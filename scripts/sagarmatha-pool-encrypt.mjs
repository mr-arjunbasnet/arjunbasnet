#!/usr/bin/env node
/*
 * Encrypt the AI or Not answer key so it can live in a PUBLIC repo.
 *
 *   node scripts/sagarmatha-pool-encrypt.mjs
 *
 * Reads  src/lib/sagarmatha/pool.local.json   (plaintext, gitignored)
 * Writes src/lib/sagarmatha/pool.enc.ts        (AES-256-GCM, committed)
 * Key:   SAGARMATHA_POOL_KEY in .env.local (32 random bytes, base64).
 *        The same value must be set in Vercel, or the game stays off.
 *
 * Image files are named with random hex and carry no metadata, so without
 * the key nobody can tell from the repo which images are AI.
 */
import { createCipheriv, randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const env = readFileSync(".env.local", "utf8");
const key = Buffer.from((env.match(/^SAGARMATHA_POOL_KEY=(.+)$/m) || [])[1]?.trim() ?? "", "base64");
if (key.length !== 32) throw new Error("SAGARMATHA_POOL_KEY in .env.local must be 32 bytes, base64");

const pool = JSON.parse(readFileSync("src/lib/sagarmatha/pool.local.json", "utf8"));
const iv = randomBytes(12);
const c = createCipheriv("aes-256-gcm", key, iv);
const ct = Buffer.concat([c.update(JSON.stringify(pool), "utf8"), c.final()]);
const blob = Buffer.concat([iv, c.getAuthTag(), ct]).toString("base64");

writeFileSync(
  "src/lib/sagarmatha/pool.enc.ts",
  `// Generated by scripts/sagarmatha-pool-encrypt.mjs. Do not edit.\n// The AI or Not answer key, encrypted (AES-256-GCM, key in SAGARMATHA_POOL_KEY).\nexport const POOL_ENC =\n  "${blob}";\n`,
);
console.log(`encrypted ${pool.length} images → src/lib/sagarmatha/pool.enc.ts`);
